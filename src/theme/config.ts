export function createAppTheme(mode: ThemeMode = "light"): ThemeConfig {
  const p = designSystem[mode];
  return {
    algorithm: mode === "dark" ? theme.darkAlgorithm : theme.defaultAlgorithm,
    cssVar: { key: "complyvault" },
    token: {
      colorPrimary: designSystem.brand,
      colorSuccess: "#22c55e",
      colorWarning: "#d97706",
      colorError: "#ef4444",
      colorInfo: "#2563eb",
      colorBgLayout: p.page,
      colorBgContainer: p.card,
      colorBgElevated: p.card,
      colorText: p.text,
      colorTextSecondary: p.secondary,
      colorTextTertiary: p.muted,
      colorBorder: p.border,
      colorBorderSecondary: p.border,
      fontFamily: designSystem.fontFamily,
      fontSize: designSystem.fontSize,
      borderRadius: designSystem.borderRadius,
      controlHeight: designSystem.controlHeight,
    },
    components: {
      Button: { fontWeight: 500, primaryShadow: "none" },
      Card: { bodyPadding: 24, headerFontSize: 16 },
      Table: {
        headerBg: p.page,
        rowHoverBg: mode === "dark" ? "#203328" : "#f0f7f3",
      },
      Layout: {
        bodyBg: p.page,
        headerBg: p.card,
        siderBg: designSystem.sidebar.bg,
      },
      Modal: { borderRadiusLG: designSystem.borderRadius + 4 },
    },
  };
}
